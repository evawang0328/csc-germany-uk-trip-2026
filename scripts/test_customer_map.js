const fs=require('node:fs'),path=require('node:path'),assert=require('node:assert/strict');
const root=path.resolve(__dirname,'..');
const {filterLocations,sortLocations,located,mapsURL}=require('../assets/customer-map.js');
const data=JSON.parse(fs.readFileSync(path.join(root,'customer_locations.json'),'utf8'));
const html=fs.readFileSync(path.join(root,'index.html'),'utf8');
assert.equal(new Set(data.locations.map(x=>x.key)).size,data.locations.length,'Unique site IDs');
for(const x of data.locations){
 assert(x.name&&x.customer_key&&x.city&&x.address&&x.verified_at,'Complete sourced location');
 assert(['DE','UK'].includes(x.country));
 assert(['customer','trader'].includes(x.role));
 assert(['address','postcode','city','street'].includes(x.precision));
 assert(located(x),x.name+' coordinates must be finite');
 assert(x.country==='DE'?x.lat>47&&x.lat<55&&x.lng>5&&x.lng<16:x.lat>49&&x.lat<60&&x.lng>-8&&x.lng<2,x.name+' country bounds');
 assert(new URL(x.source_url).protocol==='https:');
 assert(new URL(x.coordinate_source_url).protocol==='https:');
 if(x.precision==='postcode')assert(x.location_note.includes('郵遞區號'),'Approximate marker must be labelled');
 const url=new URL(mapsURL(x));assert.equal(url.searchParams.get('api'),'1');assert.equal(url.searchParams.get('destination'),x.address);
}
const germany=filterLocations(data.locations,'DE',''),uk=filterLocations(data.locations,'UK','');
assert(germany.length&&uk.length);
assert.equal(germany[0].customer_key,'DUFERCO');assert.equal(uk[0].customer_key,'BELMONT');
assert.deepEqual(germany.slice(1).map(x=>x.name),germany.slice(1).map(x=>x.name).sort((a,b)=>a.localeCompare(b,'en')));
assert.equal(filterLocations(data.locations,'UK','arcelormittal')[0].customer_key,'AMDS');
assert.equal(filterLocations(data.locations,'DE','kiffward')[0].customer_key,'KNAUF');
assert.equal(filterLocations(data.locations,'UK','not-a-customer').length,0);
assert.equal(filterLocations(data.locations,'UK','duferco').length,0,'Country filtering');
assert(!located({lat:null,lng:null}));assert(!located({lat:NaN,lng:3}));
const snapshot=JSON.stringify(data.locations);sortLocations(data.locations);assert.equal(JSON.stringify(data.locations),snapshot,'Sort does not change data');
assert(html.includes('data-tab="customer-map"')&&html.includes('data-mobile-go="customer-map"')&&html.includes('id="customer-map"'),'Both navigation menus and panel');
assert(html.includes("'followup','customer-map'].forEach"),'Existing panel switching includes map');
assert(html.includes('customer-map-open-profile')&&html.includes('openClientModal(index)'),'Existing customer modal integration');
const profileArray=html.match(/PUBLIC_CLIENTS=(\[\{[\s\S]*?\}\]);renderClients\(\)/);
assert(profileArray,'Current customer profile data must exist');
const profiles=JSON.parse(profileArray[1]);
const keyStart=html.indexOf('function meetingKey(name){'),keyEnd=html.indexOf('function hasMeetingRecord',keyStart);
const customerKey=new Function(html.slice(keyStart,keyEnd)+';return meetingKey;')();
for(const x of data.locations)assert(profiles.some(p=>customerKey(p.name)===x.customer_key),x.name+' profile button target');
for(const file of ['assets/vendor/leaflet/leaflet.js','assets/vendor/leaflet/leaflet.css','assets/vendor/leaflet-markercluster/leaflet.markercluster.js','assets/vendor/leaflet-markercluster/MarkerCluster.css'])assert(fs.existsSync(path.join(root,file)));
console.log('Customer map passed: '+data.locations.length+' sourced sites, country filtering, traders, search, navigation links and existing profile integration.');
